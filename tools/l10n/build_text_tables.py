"""Builds parla_shared/lib/src/texts/i18n/texts_<language>.dart from
parla_shared/i18n/<language>.json (Azerbaijani text → translation). Run:

    python3 -I tools/l10n/build_text_tables.py
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / 'parla_shared/i18n'
OUT = ROOT / 'parla_shared/lib/src/texts/i18n'
LANGUAGES = ['tr', 'kk', 'uz', 'tk', 'ky', 'ka']


def dart_string(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for lang in LANGUAGES:
        data = json.loads((SRC / f'{lang}.json').read_text(encoding='utf-8'))
        name = 'texts' + lang[0].upper() + lang[1:]
        lines = [
            '// GENERATED by tools/l10n/build_text_tables.py from',
            f'// parla_shared/i18n/{lang}.json. Do not edit by hand.',
            '// DRAFT TRANSLATIONS, not yet checked by native speakers.',
            '',
            f'const {name} = <String, String>{{',
        ]
        for az in sorted(data):
            if data[az]:
                lines.append(f'  {dart_string(az)}: {dart_string(data[az])},')
        lines.append('};')
        (OUT / f'texts_{lang}.dart').write_text('\n'.join(lines) + '\n', encoding='utf-8')
        print(lang, len(data))


if __name__ == '__main__':
    main()
