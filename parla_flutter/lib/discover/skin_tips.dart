/// The tip for [day] in [language].
String skinTipFor(DateTime day, String language) {
  final index = DateTime.utc(
    day.year,
    day.month,
    day.day,
  ).difference(DateTime.utc(2026)).inDays;
  final tip = skinTips[index % skinTips.length];
  return switch (language) {
    'ru' => tip[1],
    'en' => tip[2],
    _ => tip[0],
  };
}
